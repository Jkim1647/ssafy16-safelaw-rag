# 긴 표현을 먼저 찾아 '최우선변제' 안의 '우선변제'처럼 겹치는 짧은 표현이 따로 잡히지 않게 한다.
_PATTERNS = {**{term: term for term in GLOSSARY}, **ALIASES}
_PATTERNS_BY_LENGTH = sorted(_PATTERNS, key=len, reverse=True)


def find_terms(text: str) -> list[tuple[str, str]]:
    """문장에 나온 용어와 풀이를 처음 나온 순서대로 돌려준다."""

    taken: list[tuple[int, int]] = []
    first_seen: dict[str, int] = {}
    for pattern in _PATTERNS_BY_LENGTH:
        start = text.find(pattern)
        while start != -1:
            end = start + len(pattern)
            if not any(start < taken_end and taken_start < end for taken_start, taken_end in taken):
                taken.append((start, end))
                term = _PATTERNS[pattern]
                first_seen[term] = min(start, first_seen.get(term, start))
            start = text.find(pattern, end)
    return [(term, GLOSSARY[term]) for term in sorted(first_seen, key=first_seen.get)]
